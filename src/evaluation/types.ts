import type { AwardKind } from "../awards/types.js";
import type { AgentHost } from "../core/types.js";
import type { MomentType } from "../moments/types.js";
import type { PresentationLocale } from "../presentation/localization.js";

export interface EvaluationMomentSnapshot {
  id: string;
  type: MomentType;
  primaryText: string;
  relatedTexts: string[];
  /** Repeated-pattern metadata retained so review UI can present tics compactly. */
  family?: string;
  count?: number;
  variants?: string[];
  funScore: number;
  confidence: number;
  selected: boolean;
  awardKind?: AwardKind;
  awardId?: string;
}

export interface PairwisePreferenceTask {
  id: string;
  sessionId: string;
  left: EvaluationMomentSnapshot;
  right: EvaluationMomentSnapshot;
  /** P3's current prediction, retained only for scoring after the human vote. */
  predictedWinnerId: string;
}

export interface SessionEvaluationCase {
  version: 1;
  sessionId: string;
  host: AgentHost;
  title?: string;
  model?: string;
  createdAt?: string;
  moments: EvaluationMomentSnapshot[];
  pairwiseTasks: PairwisePreferenceTask[];
}

export interface PairwisePreferenceVote {
  taskId: string;
  winner: "left" | "right" | "tie" | "skip";
  /** Why a pair was skipped; language-coverage skips are generated by P7 itself. */
  reason?: "human-skip" | "language-coverage";
}

export interface AwardPreferenceVote {
  awardId: string;
  verdict: "keep" | "drop" | "skip";
  fun?: 1 | 2 | 3 | 4 | 5;
}

export interface MissedMomentNote {
  text: string;
  relatedText?: string;
  note?: string;
}

export interface SessionHumanReview {
  sessionId: string;
  /** P7 presentation/review contract used when the judgment was collected. */
  protocolVersion: number;
  /** Reader language used while making the judgment. */
  presentationLocale: PresentationLocale;
  awardVotes?: AwardPreferenceVote[];
  pairwiseVotes?: PairwisePreferenceVote[];
  /** Human-supplied moments the current pipeline failed to surface. */
  missedMoments?: MissedMomentNote[];
}

export interface PairwisePreferenceSummary {
  answered: number;
  decisive: number;
  ties: number;
  skipped: number;
  /** Automatic skips caused by incomplete reader-language coverage. */
  languageCoverageSkipped: number;
  correct: number;
  accuracy: number;
  unknownTaskIds: string[];
}

export interface AwardKindCalibration {
  kind: AwardKind;
  /** All answered cards, including skip. */
  votes: number;
  decisive: number;
  skipped: number;
  kept: number;
  /** Keep rate among keep/drop judgments only. */
  keepRate: number;
  averageFun?: number;
}

export interface CalibrationReport {
  sessionsInDataset: number;
  sessionsReviewed: number;
  /** All answered award cards, including skip. */
  awardVotes: number;
  awardDecisiveVotes: number;
  awardSkipped: number;
  /** Keep rate among decisive keep/drop votes only. */
  awardKeepRate: number;
  averageAwardFun?: number;
  pairwise: PairwisePreferenceSummary;
  missedMoments: number;
  byAwardKind: AwardKindCalibration[];
  reviewCoverage: number;
}
